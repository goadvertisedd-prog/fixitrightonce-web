// Real WebRTC audio; no scripted voice, no simulated attendees and no recordings.
// Requires separately deployed, HTTPS-only token gateway and LiveKit service.
import { Room, RoomEvent, Track } from 'https://cdn.jsdelivr.net/npm/livekit-client@2.23.0/+esm';
const $=id=>document.getElementById(id);
let room=null;let microphoneOn=false;
const TOKEN_URL='https://voice.fixitrightonce.org/api/token';
const status=t=>{$('status').textContent=t};
const safeLabel=p=>p.name||p.identity||'Guest';
function render(){
  const p=$('people');p.replaceChildren();
  if(!room)return;
  const all=[room.localParticipant,...room.remoteParticipants.values()];
  for(const x of all){
    const node=document.createElement('div');node.className='person';
    const name=document.createElement('strong');
    name.textContent=(x===room.localParticipant?'You · ':'')+safeLabel(x);
    const state=document.createElement('small');
    state.textContent=x.identity==='iris-agent'?'Live AI participant (Iris)':'Live conference participant';
    node.append(name,state);p.append(node);
  }
  if(!all.some(x=>x.identity==='iris-agent'))status('Meeting connected. Iris AI worker is not connected; other people can speak live.');
  else status('Meeting connected. Iris joined as an AI participant; her voice is generated by the running model.');
}
function subscribed(track,pub,participant){
  if(track.kind!==Track.Kind.Audio)return;
  const el=track.attach();el.autoplay=true;el.dataset.livekitIdentity=participant.identity;
  $('remoteAudio').append(el);
}
function unsubscribed(track){for(const el of track.detach())el.remove();}
$('join').addEventListener('click',async()=>{
  if(room)return;
  const name=$('displayName').value.trim(), code=$('joinCode').value;
  if(name.length<2||code.length<1){status('Enter your name and the host invitation code.');return;}
  $('join').disabled=true;status('Requesting secure meeting access…');
  const meeting=new Room({adaptiveStream:true,dynacast:true});
  try{
    const response=await fetch(TOKEN_URL,{method:'POST',headers:{'Content-Type':'application/json'},
      cache:'no-store',body:JSON.stringify({code,name})});
    const result=await response.json();
    if(!response.ok||!result.token||!result.url||!String(result.url).startsWith('wss://'))throw new Error(result.error||'Connection unavailable');
    meeting.on(RoomEvent.ParticipantConnected,render);
    meeting.on(RoomEvent.ParticipantDisconnected,render);
    meeting.on(RoomEvent.TrackSubscribed,subscribed);
    meeting.on(RoomEvent.TrackUnsubscribed,unsubscribed);
    meeting.on(RoomEvent.Disconnected,()=>{status('Conference disconnected.');cleanup();});
    room=meeting;
    await room.connect(result.url,result.token);
    $('joinCode').value='';
    $('joinPanel').style.display='none';$('live').style.display='block';$('roomLabel').textContent=result.room||'Private meeting';
    for(const participant of meeting.remoteParticipants.values()){
      for(const publication of participant.trackPublications.values()){
        if(publication.track?.kind===Track.Kind.Audio)subscribed(publication.track,publication,participant);
      }
    }
    render();
  }catch(error){
    if(room===meeting)room=null;
    try{await meeting.disconnect()}catch(_){}
    status('Unable to join. The live conference server may not be configured yet, or the invitation is invalid.');
    $('join').disabled=false;
  }
});
function cleanup(){
  microphoneOn=false;$('mic').textContent='Unmute microphone';
  $('remoteAudio').replaceChildren();$('live').style.display='none';
  $('joinPanel').style.display='block';$('join').disabled=false;
  $('people').replaceChildren();room=null;
}
$('mic').addEventListener('click',async()=>{
  if(!room)return;
  $('mic').disabled=true;
  try{
    await room.localParticipant.setMicrophoneEnabled(!microphoneOn);
    microphoneOn=!microphoneOn;
    $('mic').textContent=microphoneOn?'Mute microphone':'Unmute microphone';
  }catch(_){status('Microphone unavailable. Check browser permissions.')}
  finally{$('mic').disabled=false;}
});
$('leave').addEventListener('click',async()=>{const old=room;if(!old)return;await old.disconnect();cleanup();status('You left the conference.');});
